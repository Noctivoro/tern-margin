// Writes test/fixtures.gen.luau: every fixture file as a Luau long string.
// The standalone `luau` runtime has no file IO, so tests read fixtures
// through this generated module.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "fixtures");
const extra = process.argv.slice(2); // optional local-only files, never committed

function longString(text) {
	let level = 0;
	while (text.includes("]" + "=".repeat(level) + "]")) level++;
	const eq = "=".repeat(level);
	// A long string drops one leading newline, so add one.
	return `[${eq}[\n${text}]${eq}]`;
}

const entries = [
	...readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => [f, join(dir, f)]),
	...extra.map((p) => [p.split("/").pop(), p]),
];
const body = entries
	.map(([name, path]) => `\t{ name = ${JSON.stringify(name)}, text = ${longString(readFileSync(path, "utf8"))} },`)
	.join("\n");
writeFileSync(join(here, "fixtures.gen.luau"), `-- Generated by gen-fixtures.mjs. Do not edit.\nreturn {\n${body}\n}\n`);
console.log(`wrote ${entries.length} fixtures`);
